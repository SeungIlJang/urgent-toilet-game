export const DICT = { en, ja };

let lang = 'ko';

/** 기기 언어에서 고른다. 한국어·일본어가 아니면 영어로 둔다. */
export function detectLang() {
  const n = String(globalThis.navigator?.language || '').toLowerCase();
  if (n.startsWith('ko')) return 'ko';
  if (n.startsWith('ja')) return 'ja';
  return 'en';
}

/**
 * 번역 키를 '그대로' 들고만 있는다(아무것도 안 바꾼다).
 *
 * LOOKS·WEAPONS 같은 표는 모듈이 읽히는 순간 만들어지는데, 그때는 저장된 언어를 아직 못
 * 읽었다. 거기서 t() 를 쓰면 한국어로 굳어 버리고, 설정에서 언어를 바꿔도 안 따라온다.
 * 그래서 표에는 k() 로 키만 담고, 화면에 그릴 때 t() 로 번역한다.
 * 검사 스크립트도 k() 를 번역 키로 센다.
 */
export const k = s => s;

export function setLang(l) { lang = LANGS.includes(l) ? l : 'ko'; }
export function getLang() { return lang; }

/**
 * 한국어 원문을 키로 번역을 찾는다. 없으면 한국어 그대로 — 화면이 비는 것보다 낫다.
 * vars 의 키는 {이름} 자리에 끼워 넣는다.
 */
export function t(key, vars) {
  let s = lang === 'ko' ? key : (DICT[lang]?.[key] ?? key);
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}
